import importlib

import streamlit as st

import treaty_engine as te

te = importlib.reload(te)

st.title("Re Copilot")
st.subheader("Treaty Summary")
st.caption("Upload a treaty (PDF, Word or text). A local Llama model reads it and pulls out the key terms.")

llama_up = te.ollama_available()
if llama_up:
    st.success(f"Llama is connected via Ollama ({te.OLLAMA_HOST}). The treaty stays on your machine.")
else:
    st.warning("Ollama is not running, so a basic keyword extraction is used instead. To use Llama: install Ollama, "
               f"run `ollama pull {te.DEFAULT_MODEL}`, then refresh this page.")

model = st.text_input("Ollama model", te.DEFAULT_MODEL)
up = st.file_uploader("Treaty document", type=["pdf", "docx", "txt"])
use_sample = st.checkbox("Use a sample treaty instead")

text = ""
if up is not None:
    try:
        text = te.extract_text(up.name, up.getvalue())
    except Exception as exc:
        st.error(f"Could not read that file: {exc}")
elif use_sample:
    text = te.SAMPLE

if text.strip():
    if len(text) > te.MAX_CHARS:
        st.info(f"The treaty is long; only the first {te.MAX_CHARS:,} characters are sent to the model.")
    if st.button("Summarise treaty", type="primary"):
        with st.spinner("Reading the treaty..."):
            st.session_state["treaty_result"] = te.summarise(text, model)
elif up is not None:
    st.error("No text found. Scanned PDFs need OCR first.")

if "treaty_result" in st.session_state:
    res, engine = st.session_state["treaty_result"]
    st.caption("Generated by Llama" if engine == "llama" else "Generated by keyword rules")
    st.markdown("#### Summary")
    st.write(res.get("summary", ""))
    flags = res.get("red_flags") or []
    if flags:
        st.markdown("#### Points to check")
        for f in flags:
            st.markdown(f"- {f}")
    st.markdown("#### Key terms")
    for key, label in [(k, k.replace("_", " ").capitalize()) for k in te.FIELDS]:
        st.markdown(f"**{label}:** {res.get(key, 'Not stated')}")
    st.caption("AI output can be wrong. Always check the terms against the signed wording.")
